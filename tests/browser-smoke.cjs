const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
 const browser = await chromium.launch({ executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader'] });
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[],warnings=[],requests=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='warning'||m.type()==='error')warnings.push(m.text().slice(0,500));});
 page.on('request',r=>requests.push(r.url()));
 await page.goto(process.env.KRHIN_TEST_URL || 'http://127.0.0.1:3000');
 await page.waitForFunction(()=>document.getElementById('fileInput'));
 const caps=await page.evaluate(()=>({isolated:crossOriginIsolated,encoder:typeof VideoEncoder,decoder:typeof VideoDecoder,folder:typeof showDirectoryPicker}));
 const png=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=512;c.height=512;const x=c.getContext('2d');x.fillStyle='#7393aa';x.fillRect(0,0,512,512);return c.toDataURL().split(',')[1];});
 const name='<img src=x onerror=window.__injected=1>.png';
 await page.locator('#fileInput').setInputFiles({name,mimeType:'image/png',buffer:Buffer.from(png,'base64')});
 await page.waitForFunction(()=>document.querySelectorAll('.queue-item').length===1);
 if(await page.evaluate(()=>window.__injected))throw Error('Filename injection');
 console.log('UI loaded, image imported, filename escaped:',caps);
 await page.locator('#startAllBtn').click();
 await page.waitForFunction(()=>document.querySelector('.queue-item-status')?.textContent==='Hoàn thành'||document.querySelector('.queue-item-status')?.textContent.startsWith('Lỗi:'),{},{timeout:120000});
 const status=await page.locator('.queue-item-status').textContent();
 console.log('Image processing:',status);
 if(status!=='Hoàn thành')throw Error(status);
 await page.locator('.inspect-btn').click();
 await page.waitForFunction(()=>document.getElementById('processedImg').naturalWidth>0);
 await page.screenshot({path:'build/browser-smoke.png',fullPage:true});
 console.log('Processed image:',await page.locator('#processedImg').evaluate(img=>[img.naturalWidth,img.naturalHeight]));
 console.log('Page errors:',errors,'Warnings:',warnings,'External requests:',requests.filter(u=>/^https?:/.test(u)&&!u.startsWith('http://127.0.0.1:')));
 fs.writeFileSync('build/browser-result.json',JSON.stringify({caps,status,errors,warnings,requests},null,2));
 await browser.close();
 if(errors.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1);});
